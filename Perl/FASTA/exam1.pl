# ============================================
# 程式名稱：基因序列擷取程式
# 功能：從FASTA檔案中找出所有可能的基因序列
#       (以ATG為起始密碼，TAA為終止密碼)
# ============================================

# -------- 第一部分：讀取輸入檔案名稱 --------
# $ARGV[0] 是命令列的第一個參數
# 例如執行 perl exam1.pl sequence.fasta
# 則 $ARGV[0] = "sequence.fasta"
$file = $ARGV[0];

# -------- 第二部分：開啟並讀取FASTA檔案 --------
# open 函數開啟檔案
# INPUT 是檔案掃描器，用來讀取檔案用
# "$file" 是要開啟的檔案名稱
open (INPUT,"$file");

# 初始化變數，用來儲存拉直後的DNA序列
# FASTA檔案中DNA序列是分成多行的，需要合併成一行
$one_line_DNA="";

# -------- 第三部分：逐行讀取檔案內容 --------
# while 迴圈會一行一行讀取檔案
# <INPUT> 讀取一行，存入 $line 變數
# 當檔案讀完時，迴圈結束
while ($line=<INPUT>){
	# chomp 移除行尾的換行符號 \n
	# 因為每行結尾都有 \n，不移除會影響字串處理
	chomp $line;
	
	# 使用正則表達式檢查是否為標題行
	# =~ 是配對運算子，用來比對字串
	# /^>/ 表示「以 > 開頭」
	# ^ 是錨點，表示字串開頭
	# FASTA格式的標題行都是以 > 開頭
	if ($line=~/^>/){
		# 如果是標題行，不做任何處理（跳過）
	}
	else{
		# 如果不是標題行，就是DNA序列
		# 使用 . 運算子將序列接在一起
		# 把多行的DNA序列合併成一行
		$one_line_DNA=$one_line_DNA.$line;
	}
}

# 關閉輸入檔案
# 檔案使用完畢後要關閉，釋放系統資源
close INPUT;

# -------- 第四部分：開啟輸出檔案 --------
# > 表示寫入模式，可將程式的標準輸出內容導入、新建、覆寫一個檔案。
# "gene.fasta" 是輸出的檔案名稱
# OUTPUT 是輸出檔案的代號
open (OUTPUT,">gene.fasta");

# 初始化計數器，用來計算找到幾個基因
$i=0;

# -------- 第五部分：搜尋基因序列 --------
# 使用 while 迴圈搭配正則表達式進行全域搜尋
# 
# 正則表達式說明：/ATG\w*?TAA/g
# /.../ : 正則表達式的分隔符
# ATG   : 匹配起始密碼 ATG（字面上的三個字元）
# \w    : 匹配任意「字元」(word character)，包含 A-Z, a-z, 0-9, _
# *     : 前面的 \w 出現 0 次以上
# ?     : 搜索到最短符合的序列就停止，匹配最短的字串（遇到第一個TAA就停止）
# TAA   : 匹配終止密碼 TAA（字面上的三個字元）
# g     : global，全域搜尋，找出所有符合的（不只找第一個）
#
# $& 是特殊變數，儲存「匹配成功的區段」
while ($one_line_DNA=~/ATG(\w)*?TAA/g){
	# $& 包含完整的匹配結果並輸出（ATG...TAA）
	$seq=$&;
	
	# 計算序列長度
	# length() 函數回傳字串的字元數
	$len=length($seq);
	
	# 檢查長度是否為3的倍數
	# % 是取餘數運算子
	# 因為每個密碼子(codon)由3個核苷酸組成
	# 所以有效的基因長度必須是3的倍數
	if ($len%3==0){
		# 計數器加1
		$i++;
		# 直接輸出到FASTA檔案
		# print OUTPUT 表示輸出到 OUTPUT 檔案代號
		# "$seq\n" 輸出序列並換行
		print OUTPUT "$seq\n";
	}
}

